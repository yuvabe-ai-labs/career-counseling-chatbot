// Regenerates src/situation/prompt-v3.ts from prompts/conversation-context-v3.md. The prompt is
// embedded as a TS string because the Lambda build bundles only TypeScript (plan §16.2 F1).
// Run after editing the Markdown: pnpm --filter @yuvapath/clusterfit sync-prompt
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const markdown = readFileSync(join(root, "prompts/conversation-context-v3.md"), "utf8").replace(
  /\r\n/g,
  "\n",
);
writeFileSync(
  join(root, "src/situation/prompt-v3.ts"),
  `// GENERATED by scripts/sync-prompt.mjs from prompts/conversation-context-v3.md. Do not edit.\n` +
    `export const PROMPT_FILE_V3 = ${JSON.stringify(markdown)};\n`,
);
console.log("prompt-v3.ts regenerated");
